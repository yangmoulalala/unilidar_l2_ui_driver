"""Geometry helpers: turn a (aux, distance) packet pair into XYZ points."""

from __future__ import annotations

import math
import struct
from dataclasses import dataclass
from typing import Optional

import numpy as np

from .protocol import AuxPacket, DistancePacket

POINTS_PER_SCAN = 120


@dataclass
class Calibration:
    """Defaults follow the official unilidar_sdk."""
    range_scale: float = 0.001
    range_bias: float = 0.0
    range_min: float = 0.0
    range_max: float = 50.0
    rotate_yaw_bias_deg: float = -38.5
    z_bias: float = 0.0445


def scan_to_points(aux: AuxPacket, dist: DistancePacket,
                   cal: Calibration = Calibration()) -> np.ndarray:
    """Convert one scan into an (N, 4) float32 array of x, y, z, intensity.

    Mirrors parseRangeAuxiliaryDataToCloud() from the official SDK.
    Distances are millimetres; intensity is the raw 0..255 reflectance.
    """
    ranges = np.frombuffer(struct.pack("<120H", *dist.ranges), dtype="<u2").astype(np.float64)
    rng = ranges * cal.range_scale + cal.range_bias
    reflect = np.frombuffer(aux.reflect_data[:POINTS_PER_SCAN], dtype=np.uint8)

    k = np.arange(POINTS_PER_SCAN, dtype=np.float64)

    theta = aux.theta_angle
    ksi = aux.ksi_angle
    st, ct = math.sin(theta), math.cos(theta)
    sk, ck = math.sin(ksi), math.cos(ksi)
    beam_bias = aux.b_axis_dist / 1000.0

    pitch = math.radians(aux.sys_vertical_angle_start) + k * math.radians(aux.sys_vertical_angle_span)
    yaw = (math.radians(aux.com_horizontal_angle_start + cal.rotate_yaw_bias_deg)
           + k * math.radians(aux.com_horizontal_angle_step / POINTS_PER_SCAN))

    sin_p, cos_p = np.sin(pitch), np.cos(pitch)
    sin_y, cos_y = np.sin(yaw), np.cos(yaw)

    A = (-ct * sk + st * sin_p * ck) * rng + beam_bias
    B = cos_p * ck * rng

    x = cos_y * A - sin_y * B
    y = sin_y * A + cos_y * B
    z = (st * sk + ct * sin_p * ck) * rng + cal.z_bias

    valid = (rng > 0.0) & (rng >= cal.range_min) & (rng <= cal.range_max)
    valid &= np.isfinite(x) & np.isfinite(y) & np.isfinite(z)

    out = np.empty((int(valid.sum()), 4), dtype=np.float32)
    out[:, 0] = x[valid]
    out[:, 1] = y[valid]
    out[:, 2] = z[valid]
    out[:, 3] = reflect[valid]
    return out


def intensity_to_rgb(intensity: np.ndarray) -> np.ndarray:
    """Grayscale uint8 colours from 0..255 intensity."""
    v = np.clip(intensity, 0, 255).astype(np.uint8)
    return np.stack((v, v, v), axis=1)


def save_ply(path: str, points: np.ndarray,
             colors: Optional[np.ndarray] = None) -> None:
    """Write a binary little-endian PLY with x, y, z, intensity, rgb.

    points: (N, 4) float array (x, y, z, intensity) or (N, 3).
    """
    pts = np.asarray(points, dtype=np.float32)
    if pts.ndim != 2 or pts.shape[1] < 3:
        raise ValueError("points must be (N,3) or (N,4)")
    n = pts.shape[0]
    inten = (np.clip(pts[:, 3], 0, 255).astype(np.uint8)
             if pts.shape[1] >= 4 else np.full(n, 255, np.uint8))
    if colors is None:
        rgb = np.stack((inten, inten, inten), axis=1)
    else:
        rgb = np.ascontiguousarray(colors, dtype=np.uint8)

    rec = np.empty(n, dtype=[("x", "<f4"), ("y", "<f4"), ("z", "<f4"),
                             ("intensity", "u1"), ("red", "u1"),
                             ("green", "u1"), ("blue", "u1")])
    rec["x"] = pts[:, 0]
    rec["y"] = pts[:, 1]
    rec["z"] = pts[:, 2]
    rec["intensity"] = inten
    rec["red"] = rgb[:, 0]
    rec["green"] = rgb[:, 1]
    rec["blue"] = rgb[:, 2]

    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        "comment generated by unilidar_l1\n"
        f"element vertex {n}\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "property uchar intensity\n"
        "property uchar red\n"
        "property uchar green\n"
        "property uchar blue\n"
        "end_header\n"
    )
    with open(path, "wb") as f:
        f.write(header.encode("ascii"))
        f.write(rec.tobytes())
